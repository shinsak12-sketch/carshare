// 견적서 원문 텍스트를 보고 관련 있는 섹션만 골라서 반환.
// 아무 것도 안 걸리면 빈 배열 — 이 경우 경미손상 기준만으로 판단하게 됨.
export function matchReferenceSections(estimateText: string | null): ReferenceSection[] {
  if (!estimateText) return [];
  const text = estimateText.toLowerCase();
  return REFERENCE_SECTIONS.filter((section) =>
    section.triggerKeywords.some((kw) => text.includes(kw.toLowerCase()))
  );
}
