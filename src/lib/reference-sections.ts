export function matchReferenceSections(estimateText: string | null): ReferenceSection[] {
  if (!estimateText) return [];
  const text = estimateText.toLowerCase();
  const has = (kw: string) => text.includes(kw.toLowerCase());
  return REFERENCE_SECTIONS.filter(
    (section) =>
      section.triggerKeywords.some(has) && (!section.andAnyOf || section.andAnyOf.some(has))
  );
}
