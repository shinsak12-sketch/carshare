export function strictnessBlock(level: AdjustmentStrictness): string {
  if (level === 2) return LEVEL2;
  if (level === 1) return LEVEL1;
  return "";
}

export function strictnessTag(level: AdjustmentStrictness): string {
  return level === 3 ? "" : `-s${level}`;
}
